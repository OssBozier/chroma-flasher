"""Convert 296x128 black/white/red PNGs into PackBits-compressed screen planes for Chroma 29
firmware that draws its own screens (panel_refresh.c). A plane identical to an earlier one is
stored once.

Plane layout matches the firmware's own bitmap path (board/chroma29/drawing.c):
physical line p (0..295) holds logical column x = 295 - p, 16 bytes per line,
byte j bit (7 - k) is logical row y = 8*j + k. One plane for black, one for red.

    python make_images.py out.h card_a.png card_b.png ...
"""

import sys

from PIL import Image

W, H = 296, 128


def classify(rgb):
    r, g, b = rgb
    if r > 150 and g < 110 and b < 110:
        return "red"
    if r + g + b < 3 * 128:
        return "black"
    return "white"


def planes(path):
    img = Image.open(path).convert("RGB")
    assert img.size == (W, H), f"{path} is {img.size}, expected {(W, H)}"
    px = img.load()
    black, red = bytearray(), bytearray()
    for p in range(W):
        x = W - 1 - p
        for j in range(H // 8):
            bb = rb = 0
            for k in range(8):
                c = classify(px[x, 8 * j + k])
                if c == "black":
                    bb |= 0x80 >> k
                elif c == "red":
                    rb |= 0x80 >> k
            black.append(bb)
            red.append(rb)
    return bytes(black), bytes(red)


def packbits(data):
    out, i, n = bytearray(), 0, len(data)
    while i < n:
        run = 1
        while i + run < n and run < 128 and data[i + run] == data[i]:
            run += 1
        if run >= 2:
            out += bytes([257 - run, data[i]])
            i += run
            continue
        start = i
        while i < n and i - start < 128:
            if i + 1 < n and data[i + 1] == data[i]:
                break
            i += 1
        out += bytes([i - start - 1]) + data[start:i]
    return bytes(out)


def unpackbits(data):
    out, i = bytearray(), 0
    while i < len(data):
        h = data[i]
        i += 1
        if h < 128:
            out += data[i:i + h + 1]
            i += h + 1
        elif h > 128:
            out += bytes([data[i]]) * (257 - h)
            i += 1
    return bytes(out)


def c_array(name, data):
    rows = [", ".join(f"0x{b:02x}" for b in data[i:i + 16]) for i in range(0, len(data), 16)]
    return f"static const uint8_t __code {name}[] = {{\n   " + ",\n   ".join(rows) + "\n};\n"


def main():
    out_path, pngs = sys.argv[1], sys.argv[2:]
    parts, total = ["// Generated by make_images.py; do not edit\n#include <stdint.h>\n"], 0
    seen, refs = {}, {"black": [], "red": []}   # a plane identical to an earlier one is stored once
    for n, png in enumerate(pngs):
        for plane, raw in zip(("black", "red"), planes(png)):
            if raw in seen:
                refs[plane].append(seen[raw])
                print(f"{png} {plane}: same as {seen[raw]}")
                continue
            packed = packbits(raw)
            assert unpackbits(packed) == raw
            name = seen[raw] = f"gCard{n}_{plane}"
            refs[plane].append(name)
            parts.append(f"// {png} ({plane}): {len(raw)} -> {len(packed)} bytes\n" + c_array(name, packed))
            total += len(packed)
            print(f"{png} {plane}: {len(raw)} -> {len(packed)}")
    parts.append(f"#define CARD_COUNT {len(pngs)}\n")
    parts.append("static const uint8_t __code * const __code gCardBlack[CARD_COUNT] = {"
                 + ", ".join(refs["black"]) + "};\n")
    parts.append("static const uint8_t __code * const __code gCardRed[CARD_COUNT] = {"
                 + ", ".join(refs["red"]) + "};\n")
    open(out_path, "w").write("\n".join(parts))
    print("total compressed bytes:", total)


if __name__ == "__main__":
    main()
